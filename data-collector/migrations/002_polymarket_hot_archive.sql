BEGIN;

-- Preserve experimental high-volume rows without allowing the new collector to
-- append to them.  The explicit legacy names make this forward migration
-- non-destructive on an existing Railway database; a clean deployment may drop
-- them after an optional backup.
ALTER TABLE orderbook_updates RENAME TO legacy_orderbook_updates;
ALTER TABLE orderbook_snapshots RENAME TO legacy_orderbook_snapshots;
ALTER TABLE market_snapshots RENAME TO legacy_market_snapshots;
ALTER TABLE raw_ws_messages RENAME TO legacy_raw_ws_messages;
ALTER TABLE raw_rest_payloads RENAME TO legacy_raw_rest_payloads;
ALTER TABLE event_lifecycle_events RENAME TO legacy_event_lifecycle_events;

ALTER TABLE markets
    ADD COLUMN archived BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE market_collection_tiers (
    market_id BIGINT PRIMARY KEY REFERENCES markets (id) ON DELETE CASCADE,
    tier TEXT NOT NULL CHECK (tier IN ('full_l2', 'sampled', 'metadata_only')),
    score NUMERIC NOT NULL DEFAULT 0,
    reason_codes TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    signals JSONB NOT NULL DEFAULT '{}'::JSONB,
    ceiling_binding BOOLEAN NOT NULL DEFAULT FALSE,
    first_assigned_at TIMESTAMPTZ NOT NULL,
    evaluated_at TIMESTAMPTZ NOT NULL,
    promoted_at TIMESTAMPTZ,
    demoted_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX market_collection_tiers_tier_idx
    ON market_collection_tiers (tier, score DESC, market_id);

CREATE TABLE market_collection_tier_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_id BIGINT NOT NULL REFERENCES markets (id) ON DELETE CASCADE,
    previous_tier TEXT CHECK (
        previous_tier IS NULL OR previous_tier IN ('full_l2', 'sampled', 'metadata_only')
    ),
    tier TEXT NOT NULL CHECK (tier IN ('full_l2', 'sampled', 'metadata_only')),
    score NUMERIC NOT NULL,
    reason_codes TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    ceiling_binding BOOLEAN NOT NULL DEFAULT FALSE,
    evaluated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT market_collection_tier_history_change_key
        UNIQUE (market_id, tier, evaluated_at)
);

CREATE INDEX market_collection_tier_history_market_time_idx
    ON market_collection_tier_history (market_id, evaluated_at DESC);

CREATE TABLE current_orderbooks (
    outcome_id BIGINT PRIMARY KEY REFERENCES outcomes (id) ON DELETE CASCADE,
    market_id BIGINT NOT NULL REFERENCES markets (id) ON DELETE CASCADE,
    collector_connection_id BIGINT
        REFERENCES collector_connections (id) ON DELETE SET NULL,
    valid BOOLEAN NOT NULL DEFAULT FALSE,
    source_timestamp TIMESTAMPTZ,
    exchange_timestamp TIMESTAMPTZ,
    received_at TIMESTAMPTZ NOT NULL,
    received_monotonic_ns BIGINT NOT NULL CHECK (received_monotonic_ns >= 0),
    sequence_number BIGINT,
    book_hash TEXT,
    best_bid NUMERIC CHECK (best_bid IS NULL OR best_bid BETWEEN 0 AND 1),
    best_ask NUMERIC CHECK (best_ask IS NULL OR best_ask BETWEEN 0 AND 1),
    midpoint NUMERIC CHECK (midpoint IS NULL OR midpoint BETWEEN 0 AND 1),
    spread NUMERIC CHECK (spread IS NULL OR spread >= 0),
    bid_depth NUMERIC NOT NULL DEFAULT 0 CHECK (bid_depth >= 0),
    ask_depth NUMERIC NOT NULL DEFAULT 0 CHECK (ask_depth >= 0),
    level_count INTEGER NOT NULL DEFAULT 0 CHECK (level_count >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT current_orderbooks_outcome_market_fk
        FOREIGN KEY (outcome_id, market_id) REFERENCES outcomes (id, market_id),
    CONSTRAINT current_orderbooks_bid_ask_check
        CHECK (best_bid IS NULL OR best_ask IS NULL OR best_bid <= best_ask)
);

CREATE INDEX current_orderbooks_market_idx
    ON current_orderbooks (market_id, outcome_id);
CREATE INDEX current_orderbooks_received_idx
    ON current_orderbooks (received_at DESC);

CREATE TABLE current_orderbook_levels (
    outcome_id BIGINT NOT NULL REFERENCES current_orderbooks (outcome_id) ON DELETE CASCADE,
    side TEXT NOT NULL CHECK (side IN ('buy', 'sell')),
    price NUMERIC NOT NULL CHECK (price BETWEEN 0 AND 1),
    size NUMERIC NOT NULL CHECK (size > 0),
    received_at TIMESTAMPTZ NOT NULL,
    received_monotonic_ns BIGINT NOT NULL CHECK (received_monotonic_ns >= 0),
    PRIMARY KEY (outcome_id, side, price)
);

CREATE INDEX current_orderbook_levels_best_idx
    ON current_orderbook_levels (outcome_id, side, price);

CREATE TABLE microstructure_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_id BIGINT NOT NULL REFERENCES markets (id) ON DELETE CASCADE,
    outcome_id BIGINT NOT NULL,
    tier TEXT NOT NULL CHECK (tier IN ('full_l2', 'sampled')),
    observed_at TIMESTAMPTZ NOT NULL,
    source_timestamp TIMESTAMPTZ,
    received_at TIMESTAMPTZ NOT NULL,
    best_bid NUMERIC,
    best_ask NUMERIC,
    midpoint NUMERIC,
    spread NUMERIC CHECK (spread IS NULL OR spread >= 0),
    spread_bps NUMERIC CHECK (spread_bps IS NULL OR spread_bps >= 0),
    bid_depth_top NUMERIC NOT NULL DEFAULT 0,
    ask_depth_top NUMERIC NOT NULL DEFAULT 0,
    bid_depth_1pct NUMERIC NOT NULL DEFAULT 0,
    ask_depth_1pct NUMERIC NOT NULL DEFAULT 0,
    bid_depth_total NUMERIC NOT NULL DEFAULT 0,
    ask_depth_total NUMERIC NOT NULL DEFAULT 0,
    book_imbalance NUMERIC,
    last_trade_price NUMERIC,
    recent_trade_count INTEGER NOT NULL DEFAULT 0,
    recent_trade_volume NUMERIC NOT NULL DEFAULT 0,
    recent_update_count INTEGER NOT NULL DEFAULT 0,
    persisted_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT microstructure_observations_outcome_market_fk
        FOREIGN KEY (outcome_id, market_id) REFERENCES outcomes (id, market_id),
    CONSTRAINT microstructure_observations_natural_key
        UNIQUE (outcome_id, tier, observed_at)
);

CREATE INDEX microstructure_observations_market_time_idx
    ON microstructure_observations (market_id, observed_at DESC);
CREATE INDEX microstructure_observations_time_brin_idx
    ON microstructure_observations USING BRIN (observed_at);

CREATE TABLE archive_objects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stream TEXT NOT NULL CHECK (stream <> ''),
    schema_version INTEGER NOT NULL CHECK (schema_version > 0),
    object_key TEXT NOT NULL UNIQUE CHECK (object_key <> ''),
    content_hash TEXT NOT NULL UNIQUE CHECK (content_hash <> ''),
    compression TEXT NOT NULL CHECK (compression = 'zstd'),
    row_count BIGINT NOT NULL CHECK (row_count > 0),
    uncompressed_bytes BIGINT NOT NULL CHECK (uncompressed_bytes >= 0),
    compressed_bytes BIGINT NOT NULL CHECK (compressed_bytes >= 0),
    min_source_timestamp TIMESTAMPTZ,
    max_source_timestamp TIMESTAMPTZ,
    min_received_at TIMESTAMPTZ,
    max_received_at TIMESTAMPTZ,
    partition_date DATE NOT NULL,
    partition_hour SMALLINT NOT NULL CHECK (partition_hour BETWEEN 0 AND 23),
    status TEXT NOT NULL CHECK (
        status IN ('prepared', 'uploading', 'uploaded', 'retrying', 'failed')
    ),
    local_spool_path TEXT,
    upload_attempts INTEGER NOT NULL DEFAULT 0 CHECK (upload_attempts >= 0),
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    uploaded_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT archive_objects_upload_state_check CHECK (
        (status = 'uploaded' AND uploaded_at IS NOT NULL)
        OR status <> 'uploaded'
    )
);

CREATE INDEX archive_objects_stream_time_idx
    ON archive_objects (stream, partition_date, partition_hour, status);
CREATE INDEX archive_objects_pending_idx
    ON archive_objects (created_at)
    WHERE status <> 'uploaded';

CREATE TABLE raw_rest_payloads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL CHECK (source <> ''),
    endpoint TEXT NOT NULL CHECK (endpoint <> ''),
    entity_type TEXT,
    external_key TEXT,
    requested_at TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL,
    response_timestamp TIMESTAMPTZ,
    response_timestamp_raw TEXT,
    parameters JSONB NOT NULL DEFAULT '{}'::JSONB,
    http_status SMALLINT NOT NULL CHECK (http_status BETWEEN 100 AND 599),
    content_hash TEXT NOT NULL CHECK (content_hash <> ''),
    response_bytes BIGINT NOT NULL CHECK (response_bytes >= 0),
    record_count INTEGER CHECK (record_count IS NULL OR record_count >= 0),
    archive_object_id BIGINT NOT NULL REFERENCES archive_objects (id),
    object_key TEXT NOT NULL CHECK (object_key <> ''),
    observed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT raw_rest_payloads_compact_key UNIQUE NULLS NOT DISTINCT
        (source, endpoint, external_key, content_hash)
);

CREATE INDEX raw_rest_payloads_compact_requested_idx
    ON raw_rest_payloads (source, endpoint, requested_at DESC);

CREATE TABLE storage_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collector_run_id BIGINT REFERENCES collector_runs (id) ON DELETE SET NULL,
    observed_at TIMESTAMPTZ NOT NULL,
    postgres_database_bytes BIGINT NOT NULL CHECK (postgres_database_bytes >= 0),
    postgres_growth_bytes_per_hour NUMERIC,
    major_table_bytes JSONB NOT NULL DEFAULT '{}'::JSONB,
    archive_queue_rows BIGINT NOT NULL DEFAULT 0,
    archive_queue_bytes BIGINT NOT NULL DEFAULT 0,
    archive_oldest_queued_age_seconds NUMERIC,
    archive_objects_uploaded BIGINT NOT NULL DEFAULT 0,
    archive_rows_uploaded BIGINT NOT NULL DEFAULT 0,
    archive_uncompressed_bytes BIGINT NOT NULL DEFAULT 0,
    archive_compressed_bytes BIGINT NOT NULL DEFAULT 0,
    archive_upload_failures BIGINT NOT NULL DEFAULT 0,
    archive_growth_bytes_per_hour NUMERIC,
    spool_bytes BIGINT NOT NULL DEFAULT 0,
    pressure_state TEXT NOT NULL CHECK (pressure_state IN ('normal', 'warning', 'critical')),
    details JSONB NOT NULL DEFAULT '{}'::JSONB
);

CREATE INDEX storage_metrics_observed_idx ON storage_metrics (observed_at DESC);

CREATE TABLE archive_degradation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collector_run_id BIGINT REFERENCES collector_runs (id) ON DELETE SET NULL,
    stream TEXT NOT NULL,
    priority SMALLINT NOT NULL,
    reason TEXT NOT NULL,
    rows_affected BIGINT NOT NULL DEFAULT 0,
    bytes_affected BIGINT NOT NULL DEFAULT 0,
    detected_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    resolved_at TIMESTAMPTZ,
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    CONSTRAINT archive_degradation_resolution_check
        CHECK (resolved_at IS NULL OR resolved_at >= detected_at)
);

CREATE INDEX archive_degradation_open_idx
    ON archive_degradation_events (detected_at DESC) WHERE resolved_at IS NULL;

COMMIT;
