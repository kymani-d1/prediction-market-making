CREATE TABLE IF NOT EXISTS raw_ws_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exchange TEXT NOT NULL CHECK (exchange <> '' AND exchange = lower(exchange)),
    collector_connection_id BIGINT
        REFERENCES collector_connections (id) ON DELETE SET NULL,
    channel TEXT NOT NULL CHECK (channel <> ''),
    market_id BIGINT,
    outcome_id BIGINT,
    market_external_id TEXT,
    outcome_external_id TEXT,
    message_type TEXT,
    source_timestamp TIMESTAMPTZ,
    exchange_timestamp TIMESTAMPTZ,
    source_timestamp_raw TEXT,
    exchange_timestamp_raw TEXT,
    received_at TIMESTAMPTZ NOT NULL,
    received_monotonic_ns BIGINT NOT NULL CHECK (received_monotonic_ns >= 0),
    persisted_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    sequence_number BIGINT,
    cursor TEXT,
    book_hash TEXT,
    payload JSONB NOT NULL,
    CONSTRAINT raw_ws_messages_market_exchange_fk
        FOREIGN KEY (market_id, exchange) REFERENCES markets (id, exchange),
    CONSTRAINT raw_ws_messages_outcome_market_fk
        FOREIGN KEY (outcome_id, market_id) REFERENCES outcomes (id, market_id),
    CONSTRAINT raw_ws_messages_outcome_requires_market_check
        CHECK (outcome_id IS NULL OR market_id IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS collector_checkpoints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exchange TEXT NOT NULL CHECK (exchange <> '' AND exchange = lower(exchange)),
    job TEXT NOT NULL CHECK (job <> ''),
    checkpoint_key TEXT NOT NULL DEFAULT 'default' CHECK (checkpoint_key <> ''),
    cursor TEXT,
    checkpoint_timestamp TIMESTAMPTZ,
    last_external_id TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT collector_checkpoints_natural_key UNIQUE (exchange, job, checkpoint_key)
);

