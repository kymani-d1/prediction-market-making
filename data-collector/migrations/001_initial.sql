CREATE TABLE IF NOT EXISTS candlesticks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exchange TEXT NOT NULL CHECK (exchange <> '' AND exchange = lower(exchange)),
    market_id BIGINT NOT NULL,
    outcome_id BIGINT,
    interval_seconds INTEGER NOT NULL CHECK (interval_seconds > 0),
    period_start TIMESTAMPTZ NOT NULL,
    period_end TIMESTAMPTZ NOT NULL,
    open NUMERIC CHECK (open IS NULL OR (open >= 0 AND open <= 1)),
    high NUMERIC CHECK (high IS NULL OR (high >= 0 AND high <= 1)),
    low NUMERIC CHECK (low IS NULL OR (low >= 0 AND low <= 1)),
    close NUMERIC CHECK (close IS NULL OR (close >= 0 AND close <= 1)),
    bid_open NUMERIC CHECK (bid_open IS NULL OR (bid_open >= 0 AND bid_open <= 1)),
    bid_high NUMERIC CHECK (bid_high IS NULL OR (bid_high >= 0 AND bid_high <= 1)),
    bid_low NUMERIC CHECK (bid_low IS NULL OR (bid_low >= 0 AND bid_low <= 1)),
    bid_close NUMERIC CHECK (bid_close IS NULL OR (bid_close >= 0 AND bid_close <= 1)),
    ask_open NUMERIC CHECK (ask_open IS NULL OR (ask_open >= 0 AND ask_open <= 1)),
    ask_high NUMERIC CHECK (ask_high IS NULL OR (ask_high >= 0 AND ask_high <= 1)),
    ask_low NUMERIC CHECK (ask_low IS NULL OR (ask_low >= 0 AND ask_low <= 1)),
    ask_close NUMERIC CHECK (ask_close IS NULL OR (ask_close >= 0 AND ask_close <= 1)),
    volume NUMERIC CHECK (volume IS NULL OR volume >= 0),
    open_interest NUMERIC CHECK (open_interest IS NULL OR open_interest >= 0),
    source_timestamp TIMESTAMPTZ,
    retrieved_at TIMESTAMPTZ NOT NULL,
    persisted_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    raw_data JSONB NOT NULL DEFAULT '{}'::JSONB,
    CONSTRAINT candlesticks_market_exchange_fk
        FOREIGN KEY (market_id, exchange) REFERENCES markets (id, exchange),
    CONSTRAINT candlesticks_outcome_market_fk
        FOREIGN KEY (outcome_id, market_id) REFERENCES outcomes (id, market_id),
    CONSTRAINT candlesticks_time_order_check CHECK (period_end > period_start),
    CONSTRAINT candlesticks_price_range_check CHECK (
        (high IS NULL OR low IS NULL OR high >= low)
        AND (bid_high IS NULL OR bid_low IS NULL OR bid_high >= bid_low)
        AND (ask_high IS NULL OR ask_low IS NULL OR ask_high >= ask_low)
    ),
    CONSTRAINT candlesticks_natural_key UNIQUE NULLS NOT DISTINCT
        (exchange, market_id, outcome_id, interval_seconds, period_start)
);

