BEGIN;

-- All monetary, price, probability, quantity, and rate columns intentionally use
-- unconstrained NUMERIC.  The collector converts source values with Decimal and
-- preserves the source representation in raw_data/payload JSONB.

CREATE TABLE IF NOT EXISTS series (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exchange TEXT NOT NULL CHECK (exchange <> '' AND exchange = lower(exchange)),
    external_id TEXT NOT NULL CHECK (external_id <> ''),
    ticker TEXT,
    title TEXT NOT NULL,
    category TEXT,
    frequency TEXT,
    status TEXT,
    raw_data JSONB NOT NULL DEFAULT '{}'::JSONB,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT series_exchange_external_id_key UNIQUE (exchange, external_id),
    CONSTRAINT series_id_exchange_key UNIQUE (id, exchange),
    CONSTRAINT series_seen_order_check CHECK (last_seen_at >= first_seen_at)
);

CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exchange TEXT NOT NULL CHECK (exchange <> '' AND exchange = lower(exchange)),
    external_id TEXT NOT NULL CHECK (external_id <> ''),
    series_id BIGINT,
    ticker TEXT,
    slug TEXT,
    title TEXT NOT NULL,
    description TEXT,
    category TEXT,
    status TEXT NOT NULL DEFAULT 'unknown',
    start_time TIMESTAMPTZ,
    end_time TIMESTAMPTZ,
    created_time TIMESTAMPTZ,
    updated_time TIMESTAMPTZ,
    resolution_source TEXT,
    rules TEXT,
    raw_data JSONB NOT NULL DEFAULT '{}'::JSONB,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT events_exchange_external_id_key UNIQUE (exchange, external_id),
    CONSTRAINT events_id_exchange_key UNIQUE (id, exchange),
    CONSTRAINT events_series_exchange_fk
        FOREIGN KEY (series_id, exchange) REFERENCES series (id, exchange),
    CONSTRAINT events_time_order_check
        CHECK (end_time IS NULL OR start_time IS NULL OR end_time >= start_time),
    CONSTRAINT events_seen_order_check CHECK (last_seen_at >= first_seen_at)
);

CREATE TABLE IF NOT EXISTS markets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exchange TEXT NOT NULL CHECK (exchange <> '' AND exchange = lower(exchange)),
    external_id TEXT NOT NULL CHECK (external_id <> ''),
    event_id BIGINT,
    ticker TEXT,
    slug TEXT,
    condition_id TEXT,
    question TEXT NOT NULL,
    subtitle TEXT,
    description TEXT,
    rules TEXT,
    status TEXT NOT NULL DEFAULT 'unknown',
    market_type TEXT,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    is_tradable BOOLEAN NOT NULL DEFAULT FALSE,
    clob_enabled BOOLEAN,
    enable_order_book BOOLEAN,
    accepting_orders BOOLEAN,
    negative_risk BOOLEAN NOT NULL DEFAULT FALSE,
    open_time TIMESTAMPTZ,
    close_time TIMESTAMPTZ,
    settlement_time TIMESTAMPTZ,
    result TEXT,
    settlement_value NUMERIC,
    volume NUMERIC,
    volume_24h NUMERIC,
    open_interest NUMERIC,
    liquidity NUMERIC,
    tick_size NUMERIC,
    fee_rate NUMERIC,
    price_level_structure JSONB,
    structural_metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    raw_data JSONB NOT NULL DEFAULT '{}'::JSONB,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT markets_exchange_external_id_key UNIQUE (exchange, external_id),
    CONSTRAINT markets_id_exchange_key UNIQUE (id, exchange),
    CONSTRAINT markets_event_exchange_fk
        FOREIGN KEY (event_id, exchange) REFERENCES events (id, exchange),
    CONSTRAINT markets_time_order_check
        CHECK (close_time IS NULL OR open_time IS NULL OR close_time >= open_time),
    CONSTRAINT markets_nonnegative_metrics_check CHECK (
        (volume IS NULL OR volume >= 0)
        AND (volume_24h IS NULL OR volume_24h >= 0)
        AND (open_interest IS NULL OR open_interest >= 0)
        AND (liquidity IS NULL OR liquidity >= 0)
        AND (tick_size IS NULL OR tick_size > 0)
    ),
    CONSTRAINT markets_seen_order_check CHECK (last_seen_at >= first_seen_at)
);

CREATE TABLE IF NOT EXISTS outcomes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_id BIGINT NOT NULL,
    exchange TEXT NOT NULL CHECK (exchange <> '' AND exchange = lower(exchange)),
    external_id TEXT,
    token_id TEXT,
    name TEXT NOT NULL,
    outcome_index INTEGER,
    is_winner BOOLEAN,
    last_price NUMERIC CHECK (last_price IS NULL OR (last_price >= 0 AND last_price <= 1)),
    raw_data JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT outcomes_id_market_id_key UNIQUE (id, market_id),
    CONSTRAINT outcomes_id_exchange_key UNIQUE (id, exchange),
    CONSTRAINT outcomes_market_exchange_fk
        FOREIGN KEY (market_id, exchange) REFERENCES markets (id, exchange),
    CONSTRAINT outcomes_index_check CHECK (outcome_index IS NULL OR outcome_index >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS outcomes_exchange_external_id_uidx
    ON outcomes (exchange, external_id)
    WHERE external_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS outcomes_exchange_token_id_uidx
    ON outcomes (exchange, token_id)
    WHERE token_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS outcomes_market_index_uidx
    ON outcomes (market_id, outcome_index)
    WHERE outcome_index IS NOT NULL;

CREATE TABLE IF NOT EXISTS tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exchange TEXT NOT NULL CHECK (exchange <> '' AND exchange = lower(exchange)),
    external_id TEXT,
    name TEXT NOT NULL CHECK (name <> ''),
    slug TEXT,
    raw_data JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT tags_exchange_name_key UNIQUE (exchange, name),
    CONSTRAINT tags_id_exchange_key UNIQUE (id, exchange)
);

CREATE UNIQUE INDEX IF NOT EXISTS tags_exchange_external_id_uidx
    ON tags (exchange, external_id)
    WHERE external_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS event_tags (
    event_id BIGINT NOT NULL REFERENCES events (id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (event_id, tag_id)
);

CREATE TABLE IF NOT EXISTS market_tags (
    market_id BIGINT NOT NULL REFERENCES markets (id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (market_id, tag_id)
);

-- One row per execution of a backfill, sync, live collector, migration, or
-- maintenance job.  The coverage counters are deliberately separate from
-- records_processed so operators can see discovery and subscription scope.
CREATE TABLE IF NOT EXISTS collector_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_uuid UUID,
    collector_instance_id TEXT,
    job_type TEXT NOT NULL CHECK (job_type <> ''),
    exchange TEXT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    finished_at TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'running'
        CHECK (status IN ('running', 'completed', 'failed', 'cancelled', 'partial')),
    records_processed BIGINT NOT NULL DEFAULT 0 CHECK (records_processed >= 0),
    rows_written BIGINT NOT NULL DEFAULT 0 CHECK (rows_written >= 0),
    markets_discovered BIGINT NOT NULL DEFAULT 0 CHECK (markets_discovered >= 0),
    markets_active BIGINT NOT NULL DEFAULT 0 CHECK (markets_active >= 0),
    markets_tradable BIGINT NOT NULL DEFAULT 0 CHECK (markets_tradable >= 0),
    markets_subscribed BIGINT NOT NULL DEFAULT 0 CHECK (markets_subscribed >= 0),
    markets_excluded BIGINT NOT NULL DEFAULT 0 CHECK (markets_excluded >= 0),
    error_summary TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT collector_runs_time_order_check
        CHECK (finished_at IS NULL OR finished_at >= started_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS collector_runs_run_uuid_uidx
    ON collector_runs (run_uuid)
    WHERE run_uuid IS NOT NULL;

CREATE TABLE IF NOT EXISTS collector_connections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_uuid UUID,
    collector_run_id BIGINT REFERENCES collector_runs (id) ON DELETE SET NULL,
    collector_instance_id TEXT,
    exchange TEXT NOT NULL CHECK (exchange <> '' AND exchange = lower(exchange)),
    channel TEXT NOT NULL CHECK (channel <> ''),
    endpoint TEXT,
    transport TEXT NOT NULL DEFAULT 'websocket',
    status TEXT NOT NULL DEFAULT 'connecting'
        CHECK (status IN ('connecting', 'connected', 'disconnected', 'failed', 'closed')),
    connected_at TIMESTAMPTZ,
    disconnected_at TIMESTAMPTZ,
    first_message_at TIMESTAMPTZ,
    last_message_at TIMESTAMPTZ,
    first_sequence BIGINT,
    last_sequence BIGINT,
    messages_received BIGINT NOT NULL DEFAULT 0 CHECK (messages_received >= 0),
    messages_dropped BIGINT NOT NULL DEFAULT 0 CHECK (messages_dropped >= 0),
    rows_written BIGINT NOT NULL DEFAULT 0 CHECK (rows_written >= 0),
    subscribed_market_count INTEGER NOT NULL DEFAULT 0 CHECK (subscribed_market_count >= 0),
    reconnect_attempt INTEGER NOT NULL DEFAULT 0 CHECK (reconnect_attempt >= 0),
    reconnect_reason TEXT,
    disconnect_reason TEXT,
    error_summary TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT collector_connections_time_order_check CHECK (
        disconnected_at IS NULL OR connected_at IS NULL OR disconnected_at >= connected_at
    ),
    CONSTRAINT collector_connections_message_time_order_check CHECK (
        last_message_at IS NULL OR first_message_at IS NULL OR last_message_at >= first_message_at
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS collector_connections_uuid_uidx
    ON collector_connections (connection_uuid)
    WHERE connection_uuid IS NOT NULL;

CREATE TABLE IF NOT EXISTS collector_connection_markets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id BIGINT NOT NULL REFERENCES collector_connections (id) ON DELETE CASCADE,
    exchange TEXT NOT NULL CHECK (exchange <> '' AND exchange = lower(exchange)),
    channel TEXT NOT NULL CHECK (channel <> ''),
    market_id BIGINT,
    outcome_id BIGINT,
    market_external_id TEXT NOT NULL CHECK (market_external_id <> ''),
    outcome_external_id TEXT,
    subscribed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    unsubscribed_at TIMESTAMPTZ,
    unsubscribe_reason TEXT,
    subscription_payload JSONB NOT NULL DEFAULT '{}'::JSONB,
    CONSTRAINT collector_connection_markets_market_exchange_fk
        FOREIGN KEY (market_id, exchange) REFERENCES markets (id, exchange),
    CONSTRAINT collector_connection_markets_outcome_market_fk
        FOREIGN KEY (outcome_id, market_id) REFERENCES outcomes (id, market_id),
    CONSTRAINT collector_connection_markets_outcome_requires_market_check
        CHECK (outcome_id IS NULL OR market_id IS NOT NULL),
    CONSTRAINT collector_connection_markets_time_order_check
        CHECK (unsubscribed_at IS NULL OR unsubscribed_at >= subscribed_at),
    CONSTRAINT collector_connection_markets_subscription_key
        UNIQUE NULLS NOT DISTINCT
        (connection_id, channel, market_external_id, outcome_external_id, subscribed_at)
);

-- Per-minute counters support the requested WebSocket-messages/minute and
-- database-rows/minute logging without scraping text logs.
CREATE TABLE IF NOT EXISTS collector_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collector_run_id BIGINT REFERENCES collector_runs (id) ON DELETE SET NULL,
    collector_instance_id TEXT,
    exchange TEXT,
    channel TEXT,
    interval_start TIMESTAMPTZ NOT NULL,
    interval_seconds INTEGER NOT NULL DEFAULT 60 CHECK (interval_seconds > 0),
    websocket_messages BIGINT NOT NULL DEFAULT 0 CHECK (websocket_messages >= 0),
    database_rows_written BIGINT NOT NULL DEFAULT 0 CHECK (database_rows_written >= 0),
    messages_dropped BIGINT NOT NULL DEFAULT 0 CHECK (messages_dropped >= 0),
    markets_discovered BIGINT NOT NULL DEFAULT 0 CHECK (markets_discovered >= 0),
    markets_active BIGINT NOT NULL DEFAULT 0 CHECK (markets_active >= 0),
    markets_tradable BIGINT NOT NULL DEFAULT 0 CHECK (markets_tradable >= 0),
    markets_subscribed BIGINT NOT NULL DEFAULT 0 CHECK (markets_subscribed >= 0),
    markets_excluded BIGINT NOT NULL DEFAULT 0 CHECK (markets_excluded >= 0),
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    persisted_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT collector_metrics_bucket_key UNIQUE NULLS NOT DISTINCT
        (collector_run_id, collector_instance_id, exchange, channel, interval_start, interval_seconds)
);

-- The live cap/filter decision is recorded independently of historical
-- metadata and trade backfills.  When a cap is enabled, ranking should be
-- deterministic: liquidity DESC NULLS LAST, 24h volume DESC NULLS LAST, total
-- volume DESC NULLS LAST, then exchange/external_id ASC. ranking_criterion and config_snapshot make a
-- different future policy auditable.
CREATE TABLE IF NOT EXISTS live_market_subscription_decisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collector_run_id BIGINT REFERENCES collector_runs (id) ON DELETE SET NULL,
    exchange TEXT NOT NULL CHECK (exchange <> '' AND exchange = lower(exchange)),
    market_id BIGINT,
    market_external_id TEXT NOT NULL CHECK (market_external_id <> ''),
    evaluated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    is_active BOOLEAN NOT NULL,
    is_tradable BOOLEAN NOT NULL,
    is_eligible BOOLEAN NOT NULL,
    is_subscribed BOOLEAN NOT NULL,
    exclusion_reason TEXT,
    ranking_criterion TEXT NOT NULL DEFAULT
        'liquidity_desc_volume_24h_desc_volume_desc_exchange_external_id_asc',
    ranking_position INTEGER CHECK (ranking_position IS NULL OR ranking_position > 0),
    observed_volume NUMERIC CHECK (observed_volume IS NULL OR observed_volume >= 0),
    observed_liquidity NUMERIC CHECK (observed_liquidity IS NULL OR observed_liquidity >= 0),
    config_snapshot JSONB NOT NULL DEFAULT '{}'::JSONB,
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    persisted_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT live_market_decisions_market_exchange_fk
        FOREIGN KEY (market_id, exchange) REFERENCES markets (id, exchange),
    CONSTRAINT live_market_decisions_subscription_check
        CHECK (NOT is_subscribed OR is_eligible)
);

