BEGIN;

-- Stable deterministic integer identifiers remove repeated 64-byte condition
-- and token identifiers from high-frequency Parquet rows.  The external value
-- remains queryable here and in the low-volume archive_dictionary stream.
CREATE TABLE archive_id_dictionary (
    entity_kind TEXT NOT NULL CHECK (entity_kind IN ('market', 'token')),
    archive_key BIGINT NOT NULL CHECK (archive_key > 0),
    exchange TEXT NOT NULL DEFAULT 'polymarket',
    external_id TEXT NOT NULL CHECK (external_id <> ''),
    parent_archive_key BIGINT,
    first_observed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    last_observed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (entity_kind, archive_key),
    UNIQUE (entity_kind, exchange, external_id)
);

CREATE INDEX archive_id_dictionary_external_idx
    ON archive_id_dictionary (exchange, entity_kind, external_id);

ALTER TABLE microstructure_observations
    ADD COLUMN observation_kind TEXT NOT NULL DEFAULT 'change'
        CHECK (observation_kind IN ('change', 'heartbeat', 'periodic_hot'));

ALTER TABLE archive_objects
    ADD COLUMN payload_content_hash TEXT,
    ADD COLUMN object_role TEXT NOT NULL DEFAULT 'data'
        CHECK (object_role IN ('data', 'compacted', 'raw_rest_blob', 'dictionary')),
    ADD COLUMN compaction_generation INTEGER NOT NULL DEFAULT 0
        CHECK (compaction_generation >= 0),
    ADD COLUMN superseded_by_object_id BIGINT REFERENCES archive_objects (id),
    ADD COLUMN superseded_at TIMESTAMPTZ,
    ADD CONSTRAINT archive_objects_superseded_check CHECK (
        (superseded_by_object_id IS NULL AND superseded_at IS NULL)
        OR (superseded_by_object_id IS NOT NULL AND superseded_at IS NOT NULL)
    );

CREATE UNIQUE INDEX archive_objects_raw_rest_payload_hash_idx
    ON archive_objects (payload_content_hash)
    WHERE payload_content_hash IS NOT NULL;

CREATE INDEX archive_objects_compaction_candidates_idx
    ON archive_objects
        (stream, partition_date, partition_hour, compressed_bytes, uploaded_at)
    WHERE status = 'uploaded' AND superseded_at IS NULL
      AND object_role IN ('data', 'compacted');

ALTER TABLE raw_rest_payloads
    DROP CONSTRAINT raw_rest_payloads_compact_key;

-- Each request remains auditable even when its immutable body is reused.
ALTER TABLE raw_rest_payloads
    ADD CONSTRAINT raw_rest_payloads_request_key UNIQUE
        (source, endpoint, requested_at, content_hash);

CREATE TABLE archive_compactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stream TEXT NOT NULL,
    partition_date DATE NOT NULL,
    partition_hour SMALLINT NOT NULL CHECK (partition_hour BETWEEN 0 AND 23),
    status TEXT NOT NULL CHECK (status IN ('running', 'completed', 'failed')),
    source_object_ids BIGINT[] NOT NULL,
    replacement_object_id BIGINT REFERENCES archive_objects (id),
    objects_before INTEGER NOT NULL CHECK (objects_before >= 2),
    objects_after INTEGER NOT NULL DEFAULT 0 CHECK (objects_after >= 0),
    bytes_before BIGINT NOT NULL DEFAULT 0 CHECK (bytes_before >= 0),
    bytes_after BIGINT NOT NULL DEFAULT 0 CHECK (bytes_after >= 0),
    row_count BIGINT NOT NULL DEFAULT 0 CHECK (row_count >= 0),
    error TEXT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    completed_at TIMESTAMPTZ
);

CREATE INDEX archive_compactions_time_idx
    ON archive_compactions (started_at DESC);

CREATE TABLE market_archive_finalizations (
    market_id BIGINT PRIMARY KEY REFERENCES markets (id) ON DELETE CASCADE,
    final_snapshot_object_id BIGINT NOT NULL REFERENCES archive_objects (id),
    archived_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

-- received_at changed on every delta, so its index prevented HOT updates on
-- the tiny current-state header. Status can scan this bounded table cheaply.
DROP INDEX current_orderbooks_received_idx;
ALTER TABLE current_orderbooks SET (
    fillfactor = 80,
    autovacuum_vacuum_scale_factor = 0.05,
    autovacuum_analyze_scale_factor = 0.05
);
ALTER TABLE current_orderbook_levels SET (
    fillfactor = 85,
    autovacuum_vacuum_scale_factor = 0.05,
    autovacuum_analyze_scale_factor = 0.05
);

-- These append/delete retention tables can accumulate hundreds of thousands
-- of dead tuples before PostgreSQL's default 20% trigger fires. Keep cleanup
-- proportional to the deliberately short hot retention windows instead.
ALTER TABLE reference_price_updates SET (
    autovacuum_vacuum_threshold = 5000,
    autovacuum_vacuum_scale_factor = 0.02,
    autovacuum_analyze_threshold = 5000,
    autovacuum_analyze_scale_factor = 0.05
);
ALTER TABLE microstructure_observations SET (
    autovacuum_vacuum_threshold = 5000,
    autovacuum_vacuum_scale_factor = 0.02,
    autovacuum_analyze_threshold = 5000,
    autovacuum_analyze_scale_factor = 0.05
);

-- A multi-change exchange frame can transiently cross the reconstructed book
-- between its ordered absolute updates. Preserve that source ordering instead
-- of quarantining a valid intermediate state; individual prices remain bounded.
ALTER TABLE current_orderbooks
    DROP CONSTRAINT IF EXISTS current_orderbooks_bid_ask_check;
ALTER TABLE current_orderbooks
    DROP CONSTRAINT IF EXISTS current_orderbooks_spread_check;
ALTER TABLE current_orderbooks
    ADD CONSTRAINT current_orderbooks_price_bounds_check CHECK (
        (best_bid IS NULL OR best_bid BETWEEN 0 AND 1)
        AND (best_ask IS NULL OR best_ask BETWEEN 0 AND 1)
    );

COMMIT;
