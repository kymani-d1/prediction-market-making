BEGIN;

CREATE TABLE IF NOT EXISTS research_cohorts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exchange TEXT NOT NULL CHECK (exchange <> '' AND exchange = lower(exchange)),
    version TEXT NOT NULL CHECK (version <> ''),
    seed TEXT NOT NULL CHECK (seed <> ''),
    selection_timestamp TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    horizon_start TIMESTAMPTZ NOT NULL,
    max_markets INTEGER NOT NULL CHECK (max_markets BETWEEN 1 AND 5000),
    selected_count INTEGER NOT NULL DEFAULT 0 CHECK (selected_count >= 0),
    criteria JSONB NOT NULL DEFAULT '{}'::JSONB,
    status TEXT NOT NULL DEFAULT 'selecting'
        CHECK (status IN ('selecting', 'ready')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT research_cohorts_exchange_version_key UNIQUE (exchange, version),
    CONSTRAINT research_cohorts_selected_bound_check
        CHECK (selected_count <= max_markets)
);

CREATE TABLE IF NOT EXISTS research_cohort_markets (
    cohort_id BIGINT NOT NULL REFERENCES research_cohorts (id) ON DELETE CASCADE,
    market_id BIGINT NOT NULL REFERENCES markets (id) ON DELETE RESTRICT,
    market_external_id TEXT NOT NULL CHECK (market_external_id <> ''),
    selection_rank INTEGER NOT NULL CHECK (selection_rank > 0),
    selection_reason TEXT NOT NULL CHECK (selection_reason <> ''),
    strata JSONB NOT NULL DEFAULT '{}'::JSONB,
    selection_metrics JSONB NOT NULL DEFAULT '{}'::JSONB,
    selected_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (cohort_id, market_id),
    CONSTRAINT research_cohort_markets_rank_key
        UNIQUE (cohort_id, selection_rank),
    CONSTRAINT research_cohort_markets_external_key
        UNIQUE (cohort_id, market_external_id)
);

CREATE TABLE IF NOT EXISTS research_market_coverage (
    cohort_id BIGINT NOT NULL,
    market_id BIGINT NOT NULL,
    price_status TEXT NOT NULL DEFAULT 'not_started',
    trade_status TEXT NOT NULL DEFAULT 'not_started',
    resolution_status TEXT NOT NULL DEFAULT 'not_started',
    economics_status TEXT NOT NULL DEFAULT 'not_started',
    price_records BIGINT NOT NULL DEFAULT 0 CHECK (price_records >= 0),
    trade_records BIGINT NOT NULL DEFAULT 0 CHECK (trade_records >= 0),
    request_count BIGINT NOT NULL DEFAULT 0 CHECK (request_count >= 0),
    partial_history BOOLEAN NOT NULL DEFAULT FALSE,
    error_summary TEXT,
    provenance JSONB NOT NULL DEFAULT '{}'::JSONB,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (cohort_id, market_id),
    CONSTRAINT research_market_coverage_member_fk
        FOREIGN KEY (cohort_id, market_id)
        REFERENCES research_cohort_markets (cohort_id, market_id)
        ON DELETE CASCADE,
    CONSTRAINT research_market_coverage_price_status_check CHECK (
        price_status IN (
            'not_started', 'in_progress', 'completed', 'partial',
            'unavailable', 'retryable_failed', 'not_applicable'
        )
    ),
    CONSTRAINT research_market_coverage_trade_status_check CHECK (
        trade_status IN (
            'not_started', 'in_progress', 'completed', 'partial',
            'unavailable', 'retryable_failed', 'not_applicable'
        )
    ),
    CONSTRAINT research_market_coverage_resolution_status_check CHECK (
        resolution_status IN (
            'not_started', 'in_progress', 'completed', 'partial',
            'unavailable', 'retryable_failed', 'not_applicable'
        )
    ),
    CONSTRAINT research_market_coverage_economics_status_check CHECK (
        economics_status IN (
            'not_started', 'in_progress', 'completed', 'partial',
            'unavailable', 'retryable_failed', 'not_applicable'
        )
    )
);

CREATE INDEX IF NOT EXISTS research_cohort_markets_rank_idx
    ON research_cohort_markets (cohort_id, selection_rank);
CREATE INDEX IF NOT EXISTS research_market_coverage_status_idx
    ON research_market_coverage
        (cohort_id, price_status, trade_status, resolution_status, economics_status);

CREATE OR REPLACE VIEW research_cohort_dataset AS
SELECT c.version AS cohort_version,
       c.selection_timestamp,
       c.horizon_start,
       cm.selection_rank,
       cm.selection_reason,
       cm.strata,
       cm.selection_metrics,
       m.id AS market_id,
       m.external_id AS condition_id,
       m.slug,
       m.question,
       COALESCE(e.category, 'unknown') AS category,
       m.status,
       m.open_time,
       m.close_time,
       m.settlement_time,
       m.result,
       m.volume,
       m.liquidity,
       m.fee_rate AS current_fee_rate,
       m.raw_data -> 'feesEnabled' AS current_fees_enabled,
       m.raw_data -> 'feeSchedule' AS current_fee_schedule,
       m.raw_data ->> 'rewardsMinSize' AS current_rewards_min_size,
       m.raw_data ->> 'rewardsMaxSpread' AS current_rewards_max_spread,
       o.id AS outcome_id,
       o.external_id AS outcome_external_id,
       o.token_id,
       o.name AS outcome_name,
       o.outcome_index,
       COALESCE(
           o.is_winner,
           CASE
               WHEN lower(m.status) IN ('closed', 'resolved', 'settled', 'finalized')
                    AND o.last_price = 1 THEN TRUE
               WHEN lower(m.status) IN ('closed', 'resolved', 'settled', 'finalized')
                    AND o.last_price = 0 THEN FALSE
               ELSE NULL
           END
       ) AS is_winner,
       cov.price_status,
       cov.trade_status,
       cov.resolution_status,
       cov.economics_status,
       cov.partial_history,
       cov.price_records,
       cov.trade_records,
       cov.request_count,
       cov.provenance,
       tags.tags
FROM research_cohorts c
JOIN research_cohort_markets cm ON cm.cohort_id = c.id
JOIN markets m ON m.id = cm.market_id
LEFT JOIN events e ON e.id = m.event_id
LEFT JOIN outcomes o ON o.market_id = m.id
JOIN research_market_coverage cov
  ON cov.cohort_id = cm.cohort_id AND cov.market_id = cm.market_id
LEFT JOIN LATERAL (
    SELECT array_agg(t.name ORDER BY t.name) AS tags
    FROM market_tags mt
    JOIN tags t ON t.id = mt.tag_id
    WHERE mt.market_id = m.id
) tags ON TRUE;

COMMIT;
